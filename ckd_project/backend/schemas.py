from datetime import date
from typing import Any
from pydantic import BaseModel, ConfigDict, EmailStr, Field

# Existing ML-prediction schemas retained for the original /predict pipeline.
class BaselineData(BaseModel):
    age_at_baseline: float; gender: int; ihd: int; cvd: int; hypertension: int; diabetes: int; dyslipidemia: int
    baseline_sbp: float; baseline_dbp: float; baseline_bmi: float; baseline_egfr: float; baseline_hb: float; baseline_chol: float; baseline_tg: float; baseline_ldl: float; baseline_hdl: float; baseline_albuminuria: float
    raasi: int; glp1ra: int; sglt2i: int; statin: int
class VisitData(BaseModel):
    visit_date: str; egfr_ml_min_1_73m2: float; creatinine_mg_dl: float
class PatientRequest(BaseModel):
    baseline_data: BaselineData; visits: list[VisitData]
class PredictionResponse(BaseModel):
    status: str; risk_level: str; probability: float|None=None; egfr_trend: str; top_factors: list[dict[str, Any]]

class RegisterRequest(BaseModel):
    username: str = Field(min_length=3,max_length=100,pattern=r'^[A-Za-z0-9_.-]+$')
    email: EmailStr
    password: str = Field(min_length=10,max_length=128)
    full_name: str = Field(min_length=2,max_length=150)
    role: str = Field(pattern=r'^(DOCTOR|DEO)$')
class LoginRequest(BaseModel):
    username: str|None=None; email: EmailStr|None=None; password: str=Field(min_length=1,max_length=128)
class PatientCreate(BaseModel):
    # patient_id remains accepted for existing UI/import workflows; blank/omitted IDs are generated by the API.
    patient_id: str|None=Field(default=None,max_length=20); full_name: str=Field(min_length=1,max_length=150)
    source_code: str=Field(min_length=1,max_length=10); source_patient_id: str|None=Field(default=None,max_length=100)
    age_at_baseline: float|None=Field(default=None,ge=0,le=120); gender: int|None=Field(default=None,ge=1,le=3)
    ihd: bool|None=None; cvd: bool|None=None; hypertension: bool|None=None; diabetes: bool|None=None; dyslipidemia: bool|None=None
    baseline_sbp: float|None=Field(default=None,ge=0,le=400); baseline_dbp: float|None=Field(default=None,ge=0,le=300); baseline_bmi: float|None=Field(default=None,ge=0,le=150); baseline_egfr: float|None=Field(default=None,ge=0,le=250); baseline_hb: float|None=Field(default=None,ge=0,le=40)
    baseline_chol: float|None=None; baseline_tg: float|None=None; baseline_ldl: float|None=None; baseline_hdl: float|None=None; baseline_albuminuria: int|None=None
    raasi: bool|None=None; glp1ra: bool|None=None; sglt2i: bool|None=None; statin: bool|None=None
class LabCreate(BaseModel):
    creatinine_mg_dl: float|None=Field(default=None,ge=0,le=100); egfr_ml_min_1_73m2: float|None=Field(default=None,ge=0,le=250); acr_mg_g: float|None=Field(default=None,ge=0)
    sbp_mmhg: float|None=Field(default=None,ge=0,le=400); dbp_mmhg: float|None=Field(default=None,ge=0,le=300); hemoglobin_g_dl: float|None=Field(default=None,ge=0,le=40); hba1c_percent: float|None=Field(default=None,ge=0,le=30); glucose_mg_dl: float|None=Field(default=None,ge=0)
    cholesterol_mg_dl: float|None=None; triglycerides_mg_dl: float|None=None; ldl_mg_dl: float|None=None; hdl_mg_dl: float|None=None; potassium_mmol_l: float|None=None; sodium_mmol_l: float|None=None; albumin_g_dl: float|None=None
class VisitCreate(BaseModel):
    visit_date: date; encounter_type: str|None=Field(default='outpatient',max_length=50); labs: LabCreate
class ProfileUpdate(BaseModel):
    full_name: str=Field(min_length=2,max_length=150); email: EmailStr; hospital: str|None=Field(default=None,max_length=255)
class StatusUpdate(BaseModel):
    status: str=Field(pattern=r'^(APPROVED|REJECTED|SUSPENDED)$')
